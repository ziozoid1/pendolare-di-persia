PASSO_X, PASSO_Y = 4, 6

def larghezza(testo):
    return max(0, len(testo) * PASSO_X - 1)

def scrivi(draw, x, y, testo, colore):
    """Disegna il testo in maiuscolo. I caratteri sconosciuti diventano spazi."""
    for i, ch in enumerate(testo.upper()):
        g = G.get(ch)
        if not g:
            continue
        for ry, riga in enumerate(g.split("|")):
            for rx, c in enumerate(riga):
                if c == "#":
                    draw.point((x + i * PASSO_X + rx, y + ry), fill=colore)
